  /* Pagination — props: { total, pageSize?, page?, onPageChange? } */
  function Pagination(props) {
    const p = props || {};
    const pageSize = p.pageSize || 10;
    const pages = Math.max(1, Math.ceil((p.total || 0) / pageSize));
    let cur = Math.min(Math.max(1, p.page || 1), pages);
    const el = h('nav', { class: 'pagination', 'data-orbital': 'pagination', 'aria-label': 'Pagination' });
    const prev = h('button', { type: 'button', class: 'page-btn is-edge', 'aria-label': 'Previous' }, '‹');
    const next = h('button', { type: 'button', class: 'page-btn is-edge', 'aria-label': 'Next' }, '›');
    function window_() {
      // 1 … (cur-1) cur (cur+1) … pages
      const set = new Set([1, pages, cur, cur - 1, cur + 1]);
      const arr = [...set].filter((n) => n >= 1 && n <= pages).sort((a, b) => a - b);
      const out = []; let prevN = 0;
      arr.forEach((n) => { if (n - prevN > 1) out.push('…'); out.push(n); prevN = n; });
      return out;
    }
    function render() {
      el.innerHTML = '';
      el.append(prev);
      window_().forEach((n) => {
        if (n === '…') { el.append(h('span', { class: 'page-gap' }, '…')); return; }
        const b = h('button', { type: 'button', class: 'page-btn', 'data-state': n === cur ? 'active' : 'inactive', 'aria-current': n === cur ? 'page' : null }, String(n));
        b.addEventListener('click', () => go(n));
        el.append(b);
      });
      el.append(next);
      prev.disabled = cur === 1; next.disabled = cur === pages;
    }
    function go(n) { n = Math.min(Math.max(1, n), pages); if (n === cur) return; cur = n; render(); if (p.onPageChange) p.onPageChange(cur); }
    prev.addEventListener('click', () => go(cur - 1));
    next.addEventListener('click', () => go(cur + 1));
    render();
    return { el, get page() { return cur; }, setPage: go, get pages() { return pages; } };
  }

