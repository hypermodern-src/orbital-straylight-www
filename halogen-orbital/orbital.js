  /* =========================================================
     Combobox — text filter + selectable listbox (autocomplete)
     props: { options:[{value,label,hint?}], placeholder?, value?, onValueChange? }
     ========================================================= */
  function Combobox(props) {
    const p = props || {};
    const opts = p.options || [];
    let value = p.value || null, active = 0, openState = false;
    const input = h('input', { class: 'combobox-input', type: 'text', placeholder: p.placeholder || 'Search…', autocomplete: 'off', spellcheck: 'false', role: 'combobox', 'aria-expanded': 'false' });
    const list = h('div', { class: 'combobox-list', role: 'listbox' });
    const empty = h('div', { class: 'combobox-empty' }, 'No matches.');
    const panel = h('div', { class: 'combobox-panel', 'data-state': 'closed' }, list, empty);
    const el = h('div', { class: 'combobox', 'data-orbital': 'combobox' }, h('span', { class: 'combobox-i' }), input, panel);
    let results = opts.slice();
    function render() {
      list.innerHTML = ''; empty.style.display = results.length ? 'none' : 'block';
      results.forEach((o, i) => {
        const row = h('div', { class: 'combobox-opt', role: 'option', 'data-state': i === active ? 'active' : 'inactive', 'data-v': o.value },
          h('span', null, o.label), o.hint ? h('span', { class: 'combobox-hint' }, o.hint) : null);
        row.addEventListener('mousemove', () => { active = i; paint(); });
        row.addEventListener('mousedown', (e) => { e.preventDefault(); choose(i); });
        list.appendChild(row);
      });
    }
    function paint() { [...list.children].forEach((r, i) => r.dataset.state = i === active ? 'active' : 'inactive'); }
    function openList(o) { openState = o; panel.dataset.state = o ? 'open' : 'closed'; input.setAttribute('aria-expanded', o ? 'true' : 'false'); }
    function filter() { const q = input.value.trim().toLowerCase(); results = q ? opts.filter((o) => (o.label + ' ' + (o.hint || '')).toLowerCase().includes(q)) : opts.slice(); active = 0; render(); openList(true); }
    function choose(i) { const o = results[i]; if (!o) return; value = o.value; input.value = o.label; openList(false); if (p.onValueChange) p.onValueChange(o.value); }
    input.addEventListener('focus', filter);
    input.addEventListener('input', filter);
    input.addEventListener('blur', () => setTimeout(() => openList(false), 120));
    input.addEventListener('keydown', (e) => {
      if (e.key === 'ArrowDown') { e.preventDefault(); active = Math.min(results.length - 1, active + 1); paint(); }
      else if (e.key === 'ArrowUp') { e.preventDefault(); active = Math.max(0, active - 1); paint(); }
      else if (e.key === 'Enter') { e.preventDefault(); choose(active); }
      else if (e.key === 'Escape') openList(false);
    });
    render();
    return { el, get value() { return value; }, setValue: (v) => { const o = opts.find((x) => x.value === v); if (o) { value = v; input.value = o.label; } } };
  }

