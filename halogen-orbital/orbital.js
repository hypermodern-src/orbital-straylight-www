/* ===== orbital-motion.js ===== */
/* ============================================================
   HM MOTION — the house motion layer
   "Swiss Bank in Orbital Cyberspace"

   The sub-perceptual quality cues, extracted from the marketing
   site so every surface can inherit them. Declarative: tag markup
   with data-attributes and call ORBITAL.motion.init() (auto-runs on load).

   Crown jewels:
     [data-reveal]            entrance when scrolled into view
     [data-reveal-stagger]    on a parent → children reveal in sequence
     [data-split]             word/char-by-word text reveal
     [data-ambient]           inject slow orbital bloom field
     .orbital-sweep / .orbital-lift     hover utilities (CSS, in orbital.css)

   All gated on prefers-reduced-motion. The single easing is --ease.
   Halogen note: reveal/split map to a Hydrogen behavior whose
   activate() wires an IntersectionObserver; ambient is pure adornment.
   ============================================================ */
(function (root) {
  'use strict';
  const reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---- reveal-on-scroll (the gem) ----
     Elements with [data-reveal] start hidden and animate in when they
     enter the viewport. A parent [data-reveal-stagger] sequences its
     [data-reveal] descendants by a per-index delay. */
  let io = null;
  function ensureObserver(root_) {
    return new IntersectionObserver((entries, obs) => {
      entries.forEach((e) => {
        if (!e.isIntersecting) return;
        const el = e.target;
        const d = parseFloat(el.dataset.revealDelay || 0);
        el.style.transitionDelay = d + 'ms';
        el.setAttribute('data-reveal-state', 'in');
        obs.unobserve(el);
      });
    }, { root: root_ || null, threshold: 0.12, rootMargin: '0px 0px -8% 0px' });
  }

  function reveal(opts) {
    const o = opts || {};
    const scope = o.scope || document;
    const observer = ensureObserver(o.root);
    // assign stagger delays
    scope.querySelectorAll('[data-reveal-stagger]').forEach((parent) => {
      const step = parseFloat(parent.dataset.revealStagger) || 70;
      const base = parseFloat(parent.dataset.revealBase) || 0;
      [...parent.querySelectorAll('[data-reveal]')].forEach((el, i) => {
        if (el.dataset.revealDelay == null || el.dataset.revealDelay === '') el.dataset.revealDelay = base + i * step;
      });
    });
    scope.querySelectorAll('[data-reveal]').forEach((el) => {
      if (el.getAttribute('data-reveal-state')) return;
      if (reduce) { el.setAttribute('data-reveal-state', 'in'); return; }
      el.setAttribute('data-reveal-state', 'out');
      observer.observe(el);
    });
    return { observer };
  }
  // safety net: anything still 'out' after a beat (in a non-scrolling
  // container, or if IO never fires) is forced in — content never sticks hidden.
  function revealSafety(scope) {
    setTimeout(() => {
      (scope || document).querySelectorAll('[data-reveal-state="out"]').forEach((el) => {
        const r = el.getBoundingClientRect();
        if (r.top < window.innerHeight * 1.1) el.setAttribute('data-reveal-state', 'in');
      });
    }, 1200);
  }

  /* ---- text split: word / char reveal ----
     <h1 data-split="word"> → each word wrapped + revealed in sequence. */
  function split(el, opts) {
    const o = opts || {};
    const mode = o.mode || el.dataset.split || 'word';
    const step = o.step != null ? o.step : (parseFloat(el.dataset.splitStep) || 60);
    const base = o.base != null ? o.base : (parseFloat(el.dataset.splitBase) || 200);
    const text = el.textContent;
    el.textContent = '';
    el.classList.add('orbital-split');
    const units = mode === 'char' ? text.split('') : text.split(/(\s+)/);
    let idx = 0;
    units.forEach((u) => {
      if (/^\s+$/.test(u)) { el.appendChild(document.createTextNode(u)); return; }
      const span = document.createElement('span');
      span.className = 'orbital-split-u';
      span.textContent = u;
      if (!reduce) span.style.animationDelay = (base + idx * step) + 'ms';
      else span.style.animation = 'none';
      el.appendChild(span);
      idx++;
    });
    return el;
  }

  /* ---- ambient orbital blooms ----
     Injects a fixed, behind-everything field of slow drifting blurred
     radial gradients. ORBITAL.motion.ambient() or [data-ambient] on <body>. */
  function ambient(opts) {
    const o = opts || {};
    if (document.querySelector('.orbital-ambient')) return;
    const field = document.createElement('div');
    field.className = 'orbital-ambient';
    field.setAttribute('aria-hidden', 'true');
    const n = o.count || 2;
    for (let i = 0; i < n; i++) field.appendChild(document.createElement('i'));
    (o.target || document.body).insertBefore(field, (o.target || document.body).firstChild);
    return field;
  }

  function init(opts) {
    const o = opts || {};
    if (o.ambient || document.body.hasAttribute('data-ambient')) ambient(o.ambientOpts);
    document.querySelectorAll('[data-split]').forEach((el) => { if (!el.classList.contains('orbital-split')) split(el); });
    reveal({ scope: o.scope });
    revealSafety(o.scope);
  }

  root.ORBITAL = root.ORBITAL || {};
  root.ORBITAL.motion = { init, reveal, revealSafety, split, ambient, reduce };
  // auto-init after load unless told not to
  if (!window.__ORBITAL_NO_AUTO_MOTION) {
    if (document.readyState === 'complete' || document.readyState === 'interactive') setTimeout(init, 0);
    else window.addEventListener('DOMContentLoaded', () => init());
  }
})(window);

